const PLAN_SYSTEM: &str = "You are the planning module of a local task runner. Break the user's \
task into 3 to 8 concrete, sequential steps that can each be completed in a single written \
response. Do not plan steps that require running shell commands, executing code, browsing the \
web, or accessing files on disk; this environment has no tools. Respond with JSON only, in the \
shape {\"steps\":[{\"title\":\"short title\",\"instruction\":\"exactly what to produce\"}]}.";

const STEP_SYSTEM: &str = "You are a focused assistant executing one step of a larger task. \
Complete only the current step and return its deliverable as your entire response. You have no \
tools: you cannot run commands, browse, or edit files; produce the best written result possible \
and note anything that would require unavailable tools. Use Markdown when useful.";

fn setting_i64(ctx: &AppContext, key: &str, fallback: i64) -> i64 {
    ctx.db
        .get_setting(key)
        .ok()
        .flatten()
        .and_then(|value| value.parse::<i64>().ok())
        .unwrap_or(fallback)
}

fn resolve_target(
    ctx: &AppContext,
    task: &Task,
) -> Result<(Kind, ProviderConfig, String, String, String), AppError> {
    let conversation = task
        .conversation_id
        .as_deref()
        .and_then(|id| ctx.db.get_conversation(id).ok());
    let provider_id = task
        .provider_id
        .clone()
        .or_else(|| conversation.as_ref().and_then(|c| c.provider_id.clone()))
        .ok_or_else(|| AppError::invalid("choose a provider for this task"))?;
    let account_id = task
        .account_id
        .clone()
        .or_else(|| conversation.as_ref().and_then(|c| c.account_id.clone()));
    let model = task
        .model
        .clone()
        .or_else(|| conversation.as_ref().and_then(|c| c.model.clone()))
        .ok_or_else(|| AppError::invalid("choose a model for this task"))?;

    let target = accounts::target_for(ctx, &provider_id, account_id.as_deref(), &model)?;
    Ok((
        target.kind,
        target.config,
        target.model,
        target.provider_id,
        target.account_id,
    ))
}

fn parse_plan(text: &str, max_steps: i64) -> Option<Vec<(String, String)>> {
    let start = text.find('{')?;
    let end = text.rfind('}')?;
    if end <= start {
        return None;
    }
    let value: Value = serde_json::from_str(&text[start..=end]).ok()?;
    let items = value.get("steps")?.as_array()?;
    let mut steps = Vec::new();
    for item in items {
        let title = item
            .get("title")
            .and_then(Value::as_str)
            .unwrap_or("Step")
            .trim();
        let instruction = item
            .get("instruction")
            .and_then(Value::as_str)
            .unwrap_or("")
            .trim();
        if instruction.is_empty() {
            continue;
        }
        steps.push((
            title.chars().take(90).collect::<String>(),
            instruction.to_string(),
        ));
        if steps.len() as i64 >= max_steps.clamp(1, 12) {
            break;
        }
    }
    if steps.is_empty() {
        None
    } else {
        Some(steps)
    }
}

fn checkpoint_json(task_id: &str, steps: &[TaskStep]) -> String {
    let items: Vec<Value> = steps
        .iter()
        .map(|step| {
            json!({
                "seq": step.seq,
                "title": step.title,
                "status": step.status,
                "output": step.output,
            })
        })
        .collect();
    json!({ "taskId": task_id, "steps": items, "savedAt": now() }).to_string()
}

fn write_artifact(ctx: &AppContext, task: &Task, steps: &[TaskStep]) -> Result<(), AppError> {
    let mut report = format!("# {}\n\n", task.name);
    report.push_str("## Instructions\n\n");
    report.push_str(task.instructions.trim());
    report.push_str("\n\n");
    for step in steps {
        report.push_str(&format!("## Step {}: {}\n\n", step.seq, step.title));
        report.push_str(step.output.as_deref().unwrap_or("(no output)"));
        report.push_str("\n\n");
    }
    report.push_str(&format!("---\nGenerated by Claude Multi at {}\n", now()));
    if report.len() > 2_000_000 {
        return Err(AppError::invalid("task output is too large to save"));
    }
    let safe_name: String = task
        .name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ' ') {
                c
            } else {
                '_'
            }
        })
        .collect();
    let filename = format!("task-{}.md", safe_name.trim().replace(' ', "-"));
    let filename = crate::security::paths::sanitize_filename(&filename);
    let path = ctx.paths.artifacts_dir.join(filename);
    std::fs::write(&path, report.as_bytes())?;
    let sha256 = format!("{:x}", Sha256::digest(report.as_bytes()));
    ctx.db.insert_artifact(
        Some(&task.id),
        task.project_id.as_deref(),
        &format!("{}.md", task.name),
        &path.to_string_lossy(),
        "text/markdown",
        report.len() as i64,
        &sha256,
    )?;
    Ok(())
}

async fn complete(
    ctx: &AppContext,
    kind: Kind,
    config: &ProviderConfig,
    model: &str,
    system: &str,
    prompt: String,
    cancel: &CancellationToken,
) -> Result<Completion, ProviderError> {
    let request = ChatRequest {
        model: model.to_string(),
        messages: vec![ChatMessage::text("user", prompt)],
        system: Some(system.to_string()),
        temperature: Some(0.2),
        max_tokens: Some(setting_i64(ctx, "maxOutputTokens", 4096)),
        keep_alive: ctx.db.get_setting("ollamaKeepAlive").ok().flatten(),
    };
    tokio::select! {
        _ = cancel.cancelled() => Err(ProviderError::Cancelled),
        result = providers::complete_for(kind, &ctx.http, config, request) => result,
    }
}

async fn plan_steps(
    ctx: &AppContext,
    task: &Task,
    kind: Kind,
    config: &ProviderConfig,
    model: &str,
    cancel: &CancellationToken,
) -> Result<Vec<(String, String)>, AppError> {
    let max_steps = setting_i64(ctx, "taskMaxSteps", 8).clamp(1, 12);
    let prompt = format!(
        "Task: {}\n\nDetailed instructions:\n{}\n\nProduce at most {} steps.",
        task.name, task.instructions, max_steps
    );
    let completion = complete(ctx, kind, config, model, PLAN_SYSTEM, prompt, cancel)
        .await
        .map_err(|error| match error {
            ProviderError::Cancelled => AppError::new("cancelled", "Task planning cancelled"),
            other => AppError::new(other.code(), other.to_string()),
        })?;
    if let Some(steps) = parse_plan(&completion.content, max_steps) {
        return Ok(steps);
    }
    ctx.db.add_log(
        &task.id,
        "warn",
        "Planner did not return valid JSON; falling back to a single step",
        None,
    )?;
    Ok(vec![(
        "Complete the task".to_string(),
        task.instructions.clone(),
    )])
}

fn step_prompt(task: &Task, step: &TaskStep, completed: &[TaskStep]) -> String {
    let mut prompt = format!(
        "Overall task: {}\n\nTask instructions:\n{}\n\n",
        task.name, task.instructions
    );
    if !completed.is_empty() {
        prompt.push_str("Work completed so far:\n");
        for prior in completed {
            let output = prior.output.as_deref().unwrap_or("").trim();
            let clipped: String = output.chars().take(6000).collect();
            prompt.push_str(&format!(
                "\n### Step {}: {}\n{}\n",
                prior.seq, prior.title, clipped
            ));
        }
        prompt.push('\n');
    }
    prompt.push_str(&format!(
        "Current step ({} of the plan): {}\n\nInstruction: {}\n\nReturn the deliverable for this step now.",
        step.seq, step.title, step.instruction
    ));
    prompt
}

async fn execute(
    ctx: &AppContext,
    task_id: &str,
    cancel: &CancellationToken,
) -> Result<(), AppError> {
    let task = ctx.db.get_task(task_id)?;
    let (kind, config, model, provider_id, account_id) = resolve_target(ctx, &task)?;
    ctx.db.update_task_target(
        task_id,
        Some(&provider_id),
        Some(&account_id),
        Some(&model),
    )?;

    ctx.db.update_task_status(task_id, "running", None)?;
    ctx.db
        .add_log(task_id, "info", "Task started", None)?;

    let mut steps = ctx.db.list_steps(task_id)?;
    if steps.is_empty() {
        ctx.db
            .add_log(task_id, "info", "Planning task steps", None)?;
        match plan_steps(ctx, &task, kind, &config, &model, cancel).await {
            Ok(planned) => {
                steps = ctx.db.insert_steps(task_id, &planned)?;
                let state = checkpoint_json(task_id, &steps);
                ctx.db.insert_checkpoint(task_id, &state)?;
            }
            Err(error) if error.code == "cancelled" => {
                let paused = ctx.is_paused(task_id);
                let _ = ctx.db.update_task_status(
                    task_id,
                    if paused { "paused" } else { "cancelled" },
                    None,
                );
                return Ok(());
            }
            Err(error) => return Err(error),
        }
    }

    loop {
        if cancel.is_cancelled() {
            break;
        }
        let current = ctx.db.get_task(task_id)?;
        if matches!(current.status.as_str(), "paused" | "cancelled") {
            break;
        }
        let steps_now = ctx.db.list_steps(task_id)?;
        let next = steps_now
            .iter()
            .find(|step| !matches!(step.status.as_str(), "completed" | "skipped"))
            .cloned();
        let Some(step) = next else {
            break;
        };
        let completed: Vec<TaskStep> = steps_now
            .iter()
            .filter(|item| item.status == "completed")
            .cloned()
            .collect();

        ctx.db.set_task_current_step(task_id, step.seq)?;
        ctx.db
            .update_step_status(task_id, step.seq, "running", None, None)?;
        ctx.db.add_log(
            task_id,
            "info",
            &format!("Running step {}: {}", step.seq, step.title),
            None,
        )?;

        let prompt = step_prompt(&task, &step, &completed);
        let result = complete(ctx, kind, &config, &model, STEP_SYSTEM, prompt, cancel).await;
        match result {
            Ok(completion) => {
                ctx.db.update_step_status(
                    task_id,
                    step.seq,
                    "completed",
                    Some(&completion.content),
                    None,
                )?;
                let _ = ctx.db.insert_usage(
                    task.provider_id.as_deref(),
                    task.account_id.as_deref(),
                    Some(&model),
                    task.conversation_id.as_deref(),
                    Some(task_id),
                    completion.input_tokens.unwrap_or(0),
                    completion.output_tokens.unwrap_or(0),
                );
                let steps_after = ctx.db.list_steps(task_id)?;
                let state = checkpoint_json(task_id, &steps_after);
                ctx.db.insert_checkpoint(task_id, &state)?;
                ctx.db.add_log(
                    task_id,
                    "info",
                    &format!("Completed step {}", step.seq),
                    None,
                )?;
            }
            Err(ProviderError::Cancelled) => {
                ctx.db
                    .update_step_status(task_id, step.seq, "queued", None, None)?;
                break;
            }
            Err(error) => {
                let message = error.to_string();
                ctx.db.update_step_status(
                    task_id,
                    step.seq,
                    "failed",
                    None,
                    Some(&message),
                )?;
                ctx.db
                    .add_log(task_id, "error", &format!("Step {} failed", step.seq), Some(&message))?;
                return Err(AppError::new(error.code(), message));
            }
        }
    }

    if cancel.is_cancelled() {
        let paused = ctx.is_paused(task_id);
        let status = ctx.db.get_task(task_id)?.status;
        if !matches!(status.as_str(), "paused" | "cancelled") {
            ctx.db.update_task_status(
                task_id,
                if paused { "paused" } else { "cancelled" },
                None,
            )?;
        }
        ctx.db
            .add_log(task_id, "info", "Task paused or cancelled", None)?;
        return Ok(());
    }

    let steps_final = ctx.db.list_steps(task_id)?;
    if steps_final
        .iter()
        .all(|step| matches!(step.status.as_str(), "completed" | "skipped"))
    {
        let task_now = ctx.db.get_task(task_id)?;
        write_artifact(ctx, &task_now, &steps_final)?;
        ctx.db.update_task_status(task_id, "completed", None)?;
        ctx.db
            .add_log(task_id, "info", "Task completed", None)?;
    }
    Ok(())
}

pub fn start(ctx: Arc<AppContext>, task_id: String) -> Result<Task, AppError> {
    let task = ctx.db.get_task(&task_id)?;
    if ctx.is_task_running(&task_id) {
        return Ok(task);
    }
    if task.status == "completed" {
        return Err(AppError::invalid("this task is already completed"));
    }
    let token = ctx
        .register_task(&task_id)
        .ok_or_else(|| AppError::invalid("task is already running"))?;
    ctx.clear_pause(&task_id);
    ctx.db.update_task_status(&task_id, "running", None)?;
    ctx.db.add_log(&task_id, "info", "Task queued for execution", None)?;

    let context = ctx.clone();
    let id = task_id.clone();
    tauri::async_runtime::spawn(async move {
        let cancel = token;
        let result = execute(&context, &id, &cancel).await;
        if let Err(error) = result {
            if cancel.is_cancelled() {
                // Pause/cancel already recorded their terminal state.
            } else {
                let _ = context.db.update_task_status(&id, "failed", Some(&error.to_string()));
                let _ = context.db.add_log(
                    &id,
                    "error",
                    "Task failed",
                    Some(&error.to_string()),
                );
            }
        }
        context.finish_task(&id);
    });
    ctx.db.get_task(&task_id)
}

pub fn pause(ctx: &AppContext, task_id: &str) -> Result<Task, AppError> {
    let task = ctx.db.get_task(task_id)?;
    if !ctx.is_task_running(task_id) {
        if matches!(task.status.as_str(), "queued" | "running") {
            ctx.db.update_task_status(task_id, "paused", None)?;
        }
        return ctx.db.get_task(task_id);
    }
    ctx.request_pause(task_id);
    ctx.cancel_task(task_id);
    ctx.db.update_task_status(task_id, "paused", None)?;
    ctx.db
        .add_log(task_id, "info", "Pause requested after the current call", None)?;
    ctx.db.get_task(task_id)
}

pub fn cancel(ctx: &AppContext, task_id: &str) -> Result<Task, AppError> {
    let _ = ctx.db.get_task(task_id)?;
    if ctx.is_task_running(task_id) {
        ctx.cancel_task(task_id);
    }
    ctx.clear_pause(task_id);
    ctx.db.update_task_status(task_id, "cancelled", None)?;
    ctx.db
        .add_log(task_id, "info", "Task cancelled", None)?;
    ctx.db.get_task(task_id)
}
